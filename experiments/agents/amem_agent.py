"""
A-Mem Anchor Agent: Structured Notes + Linking + Memory Evolution.

Reproduces the *storage representation* of A-Mem (Xu et al., NeurIPS 2025,
arXiv:2502.12110) inside our fixed retrieve -> rerank -> reason pipeline. A-Mem's
defining mechanism is a Zettelkasten-style evolving memory network:

1. **Structured note construction** -- each memory is not raw text but a note
   with {content, keywords, tags, context} generated by an LLM.
2. **Linking** -- a new note is connected to the most similar existing notes,
   forming a network.
3. **Memory evolution** -- adding a new note can trigger an LLM update of the
   linked neighbours' context/tags, so old memories are re-interpreted in light
   of new ones.

The structured-note representation is markedly lossier than verbatim text
(wording is abstracted into content+tags) yet richer in organization than flat
facts, which is what makes it an informative point near the lossy end of the
fidelity curve.

FAIRNESS (controlled ablation, see paper Section 4.1): the pipeline is held
constant -- same embedder (EMBEDDING_MODEL, bge-m3), reranker, and answerer
(ANSWER_MODEL, gpt-4o); only the storage representation is swapped. The
note-construction / evolution model is the shared representation-BUILDER model
(BUILDER_MODEL, default = gpt-4o answerer as a steelman; gpt-4o-mini for the
builder-invariance check), so structure -- not builder strength -- is isolated.
"""

from typing import List, Dict, Any, Optional
import json
import time
import os

import numpy as np

from experiments.runner import Agent, AgentResponse
from experiments.data_gen import ConversationTurn
from experiments.llm_utils import call_llm_with_retry
from cogcanvas.embeddings import (
    APIEmbeddingBackend,
    MockEmbeddingBackend,
    batch_cosine_similarity,
)
from cogcanvas.reranker import Reranker
from experiments.agents._budget import (
    context_budget_chars, effective_k, fill_to_budget,
)


class Note:
    __slots__ = ("id", "content", "keywords", "tags", "context", "links", "embedding")

    def __init__(self, id, content, keywords, tags, context, embedding):
        self.id = id
        self.content = content
        self.keywords = keywords or []
        self.tags = tags or []
        self.context = context or ""
        self.links: List[int] = []
        self.embedding = embedding

    def render(self) -> str:
        kw = ", ".join(self.keywords)
        tg = ", ".join(self.tags)
        out = self.content
        if kw:
            out += f" [keywords: {kw}]"
        if tg:
            out += f" [tags: {tg}]"
        if self.context:
            out += f" [context: {self.context}]"
        return out

    def embed_text(self) -> str:
        return " ".join([self.content, " ".join(self.keywords), " ".join(self.tags)])


class AMemAgent(Agent):
    """A-Mem anchor: structured notes with linking + evolution, retrieved/
    reranked/answered through the shared pipeline."""

    def __init__(
        self,
        model: str = None,
        embedding_model: str = None,
        builder_model: str = None,
        retain_recent: int = 5,
        top_k: int = 10,
        use_reranker: bool = True,
        link_neighbors: int = 5,        # neighbours linked per new note
        evolve: bool = True,            # run memory evolution on linked neighbours
        note_window: int = 2,           # turns per note-construction call
    ):
        from dotenv import load_dotenv

        load_dotenv()

        self.retain_recent = retain_recent
        self.top_k = top_k
        self.use_reranker = use_reranker
        self.link_neighbors = link_neighbors
        self.evolve = evolve
        self.note_window = note_window

        self.model = model or os.getenv("ANSWER_MODEL") or os.getenv("MODEL_DEFAULT", "gpt-4o-mini")
        self.builder_model = (
            builder_model
            or os.getenv("BUILDER_MODEL")
            or os.getenv("ANSWER_MODEL")
            or "gpt-4o-mini"
        )

        self._client = None
        self._init_client()

        embed_model_name = embedding_model or os.getenv("EMBEDDING_MODEL", "bge-m3")
        try:
            ek = os.getenv("EMBEDDING_API_KEY") or os.getenv("API_KEY") or os.getenv("OPENAI_API_KEY")
            eb = os.getenv("EMBEDDING_API_BASE") or os.getenv("API_BASE") or os.getenv("OPENAI_API_BASE")
            self.embedder = (
                APIEmbeddingBackend(model=embed_model_name, api_key=ek, api_base=eb)
                if ek else MockEmbeddingBackend()
            )
            if not ek:
                print("Warning: EMBEDDING_API_KEY/API_KEY not set, using mock embeddings")
        except Exception as e:
            print(f"Failed to init embedding backend: {e}. Using mock.")
            self.embedder = MockEmbeddingBackend()

        self.reranker = None
        if self.use_reranker:
            try:
                rk = os.getenv("RERANKER_API_KEY") or os.getenv("EMBEDDING_API_KEY") or os.getenv("API_KEY")
                rb = os.getenv("RERANKER_API_BASE") or os.getenv("EMBEDDING_API_BASE") or os.getenv("API_BASE")
                self.reranker = (
                    Reranker(model=os.getenv("RERANKER_MODEL", "bge-reranker-v2-m3"),
                             api_key=rk, api_base=rb, use_mock=False)
                    if rk else Reranker(use_mock=True)
                )
            except Exception as e:
                print(f"Failed to init reranker: {e}. Using mock.")
                self.reranker = Reranker(use_mock=True)

        self._history: List[ConversationTurn] = []
        self._retained_history: List[ConversationTurn] = []
        self._notes: List[Note] = []
        self._next_id = 0
        self.stats = {"notes": 0, "links": 0, "evolved": 0}

    def _init_client(self):
        try:
            from openai import OpenAI

            ak = os.getenv("ANSWER_API_KEY") or os.getenv("API_KEY") or os.getenv("OPENAI_API_KEY")
            ab = os.getenv("ANSWER_API_BASE") or os.getenv("API_BASE") or os.getenv("OPENAI_API_BASE")
            if ak:
                self._client = OpenAI(api_key=ak, base_url=ab)
        except ImportError:
            pass

    @property
    def name(self) -> str:
        rr = "+rerank" if self.use_reranker else ""
        ev = "+evolve" if self.evolve else ""
        return f"A-Mem(notes+link{ev}{rr}, k={self.top_k})"

    # ---- P1-8 backbone-integrated anchor: builder interface --------------
    # Memory evolution rewrites linked neighbours' tags/context, so the canvas
    # is rebuilt from the full current note set each batch (replaces_store=True).
    anchor_label = "AMemNotes"
    replaces_store = True

    def build_items(self, turns: List[ConversationTurn], verbose: int = 0):
        """Run A-Mem's note construction + linking + evolution over this batch
        (mutating self._notes), then return the FULL current note set as items.
        Each note is rendered with its keywords/tags/context, the lossy
        structured representation under test."""
        W = self.note_window
        for i in range(0, len(turns), W):
            group = turns[i:i + W]
            for note_fields in self._construct_notes(group):
                self._add_note_with_linking(note_fields)
        return [
            {"content": n.render(), "source_turns": [], "session_datetime": None}
            for n in self._notes
        ]

    def reset(self) -> None:
        self._history = []
        self._retained_history = []
        self._notes = []
        self._next_id = 0
        self.stats = {"notes": 0, "links": 0, "evolved": 0}

    def process_turn(self, turn: ConversationTurn) -> None:
        self._history.append(turn)

    def on_compression(self, retained_turns: List[ConversationTurn]) -> None:
        turns_to_process = [t for t in self._history if t not in retained_turns]
        W = self.note_window
        for i in range(0, len(turns_to_process), W):
            group = turns_to_process[i:i + W]
            for note_fields in self._construct_notes(group):
                self._add_note_with_linking(note_fields)
        self._retained_history = retained_turns
        self._history = list(retained_turns)

    # ---- A-Mem mechanism 1: structured note construction -----------------

    @staticmethod
    def _dated_text(turns: List[ConversationTurn]) -> str:
        """Turn text with absolute-date markers so note construction CAN retain
        temporal grounding (matching the verbatim anchor's input)."""
        out = []
        for t in turns:
            sdt = getattr(t, "session_datetime", None)
            dt = f" (Session: {sdt})" if sdt else ""
            out.append(f"[Turn {t.turn_id}{dt}] User: {t.user}\nAssistant: {t.assistant}\n")
        return "".join(out)

    def _construct_notes(self, turns: List[ConversationTurn]) -> List[Dict[str, Any]]:
        if self._client is None or not turns:
            return []
        text = self._dated_text(turns)
        prompt = (
            "Convert the following conversation excerpt into structured memory "
            "notes (Zettelkasten style). For each distinct idea produce a note "
            "with: content (a concise standalone statement, pronouns resolved to "
            "names), keywords (salient terms), tags (high-level categories), and "
            "context (one short sentence on why it matters).\n"
            'Return ONLY JSON: {"notes": [{"content": "...", "keywords": ["..."], '
            '"tags": ["..."], "context": "..."}]}. If nothing salient, {"notes": []}.\n\n'
            f"{text}\nJSON:"
        )
        try:
            raw = call_llm_with_retry(
                client=self._client, model=self.builder_model,
                messages=[{"role": "user", "content": prompt}],
                max_tokens=500, temperature=0, call_type="extract",
            ).strip()
            if "{" in raw:
                raw = raw[raw.index("{"): raw.rindex("}") + 1]
            notes = json.loads(raw).get("notes", [])
            return [n for n in notes if isinstance(n, dict) and str(n.get("content", "")).strip()]
        except Exception:
            return []

    # ---- A-Mem mechanism 2+3: linking + evolution ------------------------

    def _add_note_with_linking(self, fields: Dict[str, Any]) -> None:
        content = str(fields.get("content", "")).strip()
        note = Note(
            id=self._next_id,
            content=content,
            keywords=[str(k) for k in fields.get("keywords", []) if str(k).strip()],
            tags=[str(t) for t in fields.get("tags", []) if str(t).strip()],
            context=str(fields.get("context", "")),
            embedding=None,
        )
        note.embedding = self.embedder.embed(note.embed_text())
        self._next_id += 1

        neighbors = []
        if self._notes:
            sims = batch_cosine_similarity(note.embedding, [n.embedding for n in self._notes])
            order = sorted(range(len(self._notes)), key=lambda i: sims[i], reverse=True)
            neighbors = [self._notes[i] for i in order[: self.link_neighbors]]
            for nb in neighbors:
                note.links.append(nb.id)
                nb.links.append(note.id)
                self.stats["links"] += 1

        self._notes.append(note)
        self.stats["notes"] += 1

        if self.evolve and neighbors:
            self._evolve_neighbors(note, neighbors)

    def _evolve_neighbors(self, new_note: Note, neighbors: List[Note]) -> None:
        """LLM re-interprets linked neighbours' context/tags given the new note."""
        if self._client is None:
            return
        listing = "\n".join(
            f'{{"id": {n.id}, "content": "{n.content}", "tags": {json.dumps(n.tags)}, '
            f'"context": "{n.context}"}}'
            for n in neighbors
        )
        prompt = (
            "A NEW memory note was just added. In light of it, you MAY refine the "
            "tags and context of the existing linked notes (only if the new note "
            "changes how they should be interpreted). Do not change their content.\n\n"
            f'NEW note: {{"content": "{new_note.content}", "tags": {json.dumps(new_note.tags)}}}\n\n'
            f"EXISTING linked notes:\n{listing}\n\n"
            'Return ONLY JSON: {"updates": [{"id": <id>, "tags": ["..."], "context": "..."}]}. '
            'Include only notes you actually changed; {"updates": []} if none.'
        )
        try:
            raw = call_llm_with_retry(
                client=self._client, model=self.builder_model,
                messages=[{"role": "user", "content": prompt}],
                max_tokens=400, temperature=0, call_type="extract",
            ).strip()
            if "{" in raw:
                raw = raw[raw.index("{"): raw.rindex("}") + 1]
            updates = json.loads(raw).get("updates", [])
            by_id = {n.id: n for n in neighbors}
            for u in updates:
                nid = u.get("id")
                nid = int(nid) if nid is not None and str(nid).strip() != "" else None
                if nid in by_id:
                    n = by_id[nid]
                    if u.get("tags"):
                        n.tags = [str(t) for t in u["tags"]]
                    if u.get("context"):
                        n.context = str(u["context"])
                    n.embedding = self.embedder.embed(n.embed_text())
                    self.stats["evolved"] += 1
        except Exception:
            return

    # ---- retrieval / answer (pipeline-constant) --------------------------

    def answer_question(self, question: str) -> AgentResponse:
        start = time.time()
        retrieved, scores = [], []
        budget = context_budget_chars()
        eff_k = effective_k(self.top_k, budget)
        if self._notes:
            q_emb = self.embedder.embed(question)
            sims = batch_cosine_similarity(q_emb, [n.embedding for n in self._notes])
            ranked = sorted(zip(self._notes, sims), key=lambda x: x[1], reverse=True)
            if self.use_reranker and self.reranker is not None:
                cand_k = min(eff_k * 2, len(ranked))
                cand = [n for n, _ in ranked[:cand_k]]
                rr = self.reranker.rerank(question, [n.render() for n in cand], top_k=eff_k)
                retrieved = [cand[idx] for idx, _ in rr]
                scores = [sc for _, sc in rr]
            else:
                top = ranked[:eff_k]
                retrieved = [n for n, _ in top]
                scores = [sc for _, sc in top]
            keep = len(fill_to_budget(retrieved, lambda n: n.render(), budget))
            retrieved, scores = retrieved[:keep], scores[:keep]

        parts = []
        if retrieved:
            parts.append("## Retrieved Memory (structured notes from earlier conversation)")
            for n in retrieved:
                parts.append(f"- {n.render()}")
            parts.append("")
        if self._history:
            parts.append("## Recent Conversation")
            for t in self._history:
                parts.append(f"User: {t.user}")
                parts.append(f"Assistant: {t.assistant}")
                parts.append("")
        context = "\n".join(parts) if parts else "[No context available]"

        answer = self._generate_answer(context, question)
        latency = (time.time() - start) * 1000
        return AgentResponse(
            answer=answer,
            latency_ms=latency,
            metadata={
                "retrieved_notes": len(retrieved),
                "store_size": len(self._notes),
                "stats": dict(self.stats),
                "top_score": scores[0] if scores else 0.0,
            },
        )

    def _generate_answer(self, context: str, question: str) -> str:
        prompt = f"""You are an expert reasoning agent. Your goal is to answer the user's question by connecting discrete facts from the retrieved information.

## Retrieved Context
{context}

## Instructions
1. Analyze the retrieved information carefully
2. Even if pieces of information are not explicitly linked, use your reasoning to infer relationships
3. Synthesize a complete answer that explains the reasoning process

## Question
{question}

## Answer
"""
        if self._client is None:
            return "I don't have enough information."
        try:
            return call_llm_with_retry(
                client=self._client, model=self.model,
                messages=[{"role": "user", "content": prompt}],
                max_tokens=200, temperature=0, call_type="gen",
            )
        except Exception as e:
            return f"Error: {e}"
